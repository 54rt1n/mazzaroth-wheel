test('pole presets fill dates and Custom unlocks the epoch and updates the sky', async ({ page }) => {
  const year = page.locator('#observer-year')
  const era = page.locator('#observer-era')
  await expect(page.locator('#center-controls #observer-year')).toHaveCount(1)
  await expect(year).toBeDisabled()
  for (const [name, value, period] of [['Thuban', '2799', 'bce'], ['Kochab', '1061', 'bce'], ['Polaris', '2102', 'ce']]) {
    await page.getByLabel(name, { exact: true }).check()
    await expect(year).toHaveValue(value)
    await expect(era).toHaveValue(period)
    await expect(year).toBeDisabled()
    await expect(era).toBeDisabled()
  }
  await page.getByLabel('Custom', { exact: true }).check()
  await expect(year).toHaveValue('1200')
  await expect(year).toBeEnabled()
  await expect(era).toBeEnabled()
  const before = await page.locator('.background-star').first().getAttribute('cx')
  await year.fill('900')
  await year.dispatchEvent('change')
  await era.selectOption('ce')
  await expect(page.locator('#observer-status')).toContainText('900 CE')
  await expect(page.locator('.background-star').first()).not.toHaveAttribute('cx', before!)
  await page.getByRole('link', { name: 'Ground sky', exact: true }).click()
  await expect(page.getByLabel('Custom', { exact: true })).toBeChecked()
  await expect(year).toHaveValue('900')
  await expect(era).toHaveValue('ce')
  await page.getByLabel('Thuban', { exact: true }).check()
  await expect(year).toHaveValue('2799')
  await page.getByLabel('Custom', { exact: true }).check()
  await expect(year).toHaveValue('900')
  await expect(era).toHaveValue('ce')
  await page.getByLabel('Celestial pole', { exact: true }).check()
  await expect(year).toHaveValue('1200')
  await expect(era).toHaveValue('bce')
  await expect(year).toBeDisabled()
  await page.getByRole('link', { name: 'Atlas', exact: true }).click()
  await page.locator('#observer-enabled').uncheck()
  await page.getByLabel('Custom', { exact: true }).check()
  await expect(page.locator('#observer-status')).toHaveText('Custom epoch sky; observer overlay off.')
  await expect(page.locator('#frame-label')).toContainText('900 CE')
})

test('the equinox stays fixed as the epoch changes while the stars move', async ({ page }) => {
  await page.getByLabel('Custom', { exact: true }).check()
  await page.locator('#observer-enabled').uncheck()
  const equinox = page.locator('.equinox-marker')
  await expect(equinox).toHaveAttribute('transform', 'translate(0,-177.5)')
  await expect(equinox.locator('text')).toHaveText('Spring equinox')
  const marker = await equinox.getAttribute('transform')
  const slot = await page.locator('.blend-slot circle').first().getAttribute('cx')
  const star = await page.locator('.background-star').first().getAttribute('cx')
  await page.locator('#observer-year').fill('2000')
  await page.locator('#observer-year').dispatchEvent('change')
  await page.locator('#observer-era').selectOption('ce')
  await expect(equinox).toHaveAttribute('transform', marker!)
  await expect(page.locator('.blend-slot circle').first()).toHaveAttribute('cx', slot!)
  await expect(page.locator('.background-star').first()).not.toHaveAttribute('cx', star!)
  // The marker is a celestial reference, so a manual view rotation moves it too.
  await page.locator('#rotation').fill('45')
  await page.locator('#rotation').dispatchEvent('input')
  await expect(equinox).not.toHaveAttribute('transform', marker!)
  await page.locator('#toggle-labels').click()
  await expect(equinox.locator('text')).toHaveCount(0)
  await expect(equinox.locator('circle')).toHaveCount(1)
  await page.getByLabel('Thuban', { exact: true }).check()
  await expect(equinox.locator('title')).toContainText('Ephemeris equinox')
})

