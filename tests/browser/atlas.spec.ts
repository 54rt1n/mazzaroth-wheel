test('zoom resizes the complete wheel and keeps the rim, labels and stars together', async ({ page }) => {
  const svg = page.locator('#sky-wheel')
  await svg.scrollIntoViewIfNeeded()
  const frame = (await svg.boundingBox())!
  const rim = page.locator('.atlas-rim')
  const initial = (await rim.boundingBox())!.width
  await page.mouse.move(frame.x + frame.width / 2, frame.y + frame.height / 2)
  await page.mouse.wheel(0, -400)
  await expect.poll(async () => (await rim.boundingBox())!.width).toBeGreaterThan(initial * 1.5)
  const firstZoom = (await rim.boundingBox())!.width
  // This lies outside the original circle but inside the enlarged wheel.
  await page.mouse.move(frame.x + frame.width * 0.95, frame.y + frame.height / 2)
  await page.mouse.wheel(0, -100)
  await expect.poll(async () => (await rim.boundingBox())!.width).toBeGreaterThan(firstZoom * 1.1)
  const scale = await page.evaluate(() => {
    const scaleOf = (selector: string) => {
      const matrix = document.querySelector<SVGGraphicsElement>(selector)!.getScreenCTM()!
      return Math.hypot(matrix.a, matrix.b)
    }
    return ['.atlas-rim', '.atlas-coordinates text', '.background-star'].map(scaleOf)
  })
  expect(scale[0]).toBeCloseTo(scale[1], 8)
  expect(scale[0]).toBeCloseTo(scale[2], 8)
  const zoomed = (await rim.boundingBox())!.width
  await page.locator('#search').fill('pleiades')
  await expect.poll(async () => (await rim.boundingBox())!.width).toBeCloseTo(zoomed, 5)
  await page.getByRole('link', { name: 'Register', exact: true }).click()
  await expect(page.locator('#register-panel')).toBeVisible()
  await page.getByRole('link', { name: 'Atlas', exact: true }).click()
  await expect(svg).toBeVisible()
  await expect.poll(async () => (await rim.boundingBox())?.width ?? 0).toBeCloseTo(zoomed, 5)
  await page.getByRole('button', { name: 'Reset sky orientation', exact: true }).click()
  await expect.poll(async () => (await rim.boundingBox())!.width).toBeCloseTo(initial, 5)
})

