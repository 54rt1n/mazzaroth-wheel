test('offline file runs without network and retains downloadable source data', async ({ page, context }) => {
  await context.setOffline(true)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(pathToFileURL(resolve('dist/mazzaroth-wheel.html')).href)
  await expect(page.locator('#explorer')).toHaveAttribute('aria-busy', 'false')
  await expect(page.locator('.blend-slot')).toHaveCount(36)
  await page.getByRole('link', { name: 'Ground sky', exact: true }).click()
  await expect(page.locator('#ground-panel')).toBeVisible()
  await expect(page.locator('#ground-tradition option')).toHaveCount(13)
  const data = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Constellation dataset', exact: false }).click()
  expect((await data).suggestedFilename()).toBe('constellations.json')
  const sources = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Source files', exact: false }).click()
  expect((await sources).suggestedFilename()).toBe('constellation-sources.zip')
  await page.locator('#open-sources').click()
  const license = page.waitForEvent('download')
  await page.getByRole('link', { name: 'PolyForm Noncommercial License 1.0.0', exact: true }).click()
  expect((await license).suggestedFilename()).toMatch(/^LICENSE(?:\.txt)?$/)
  const notices = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Third-party notices and licenses', exact: true }).click()
  expect((await notices).suggestedFilename()).toBe('THIRD_PARTY_NOTICES.txt')
  await page.getByRole('button', { name: 'Close sources', exact: true }).click()
  await page.getByRole('link', { name: 'Register', exact: true }).click()
  await expect(page.locator('#register-body tr')).toHaveCount(36)
  expect(errors).toEqual([])
})

